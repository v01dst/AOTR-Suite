<#
	AOTR Suite :: build
	Bundles the modular sources into a single file that can be pasted into
	an executor.

	Usage:
		powershell -ExecutionPolicy Bypass -File tools\build.ps1
#>

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root "src"
$vendor = Join-Path $root "vendor"
$dist = Join-Path $root "dist"
$outFile = Join-Path $dist "AOTR.lua"

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Read-Lua([string]$path) {
	$text = [System.IO.File]::ReadAllText($path)
	# Strip a byte order mark if the file happens to have one.
	if ($text.Length -gt 0 -and $text[0] -eq [char]0xFEFF) {
		$text = $text.Substring(1)
	}
	return $text
}

# Module order only decides the order of the definitions, every module
# resolves its dependencies at runtime.
$modules = [ordered]@{
	"Util"            = Join-Path $src "Util.lua"
	"Config"          = Join-Path $src "Config.lua"
	"Remotes"         = Join-Path $src "Remotes.lua"
	"GameUI"          = Join-Path $src "GameUI.lua"
	"Targets"         = Join-Path $src "Targets.lua"
	"Stats"           = Join-Path $src "Stats.lua"
	"Safety"          = Join-Path $src "Safety.lua"
	"Webhook"         = Join-Path $src "Webhook.lua"
	"Farm"            = Join-Path $src "Features\Farm.lua"
	"Combat"          = Join-Path $src "Features\Combat.lua"
	"Reload"          = Join-Path $src "Features\Reload.lua"
	"Claim"           = Join-Path $src "Features\Claim.lua"
	"Boosts"          = Join-Path $src "Features\Boosts.lua"
	"AutoStart"       = Join-Path $src "Features\AutoStart.lua"
	"Waves"           = Join-Path $src "Features\Waves.lua"
	"ShadowBan"       = Join-Path $src "Features\ShadowBan.lua"
	"FallbackUI"      = Join-Path $src "FallbackUI.lua"
	"Diagnostics"     = Join-Path $src "Diagnostics.lua"
	"Hub"             = Join-Path $src "Hub.lua"
	"main"            = Join-Path $src "main.lua"
}

$builder = New-Object System.Text.StringBuilder

function Add-Line([string]$line) {
	[void]$builder.AppendLine($line)
}

Add-Line "--[["
Add-Line "	AOTR Suite :: Attack on Titan: Revolution"
Add-Line ""
Add-Line "	Bundled build. Generated by tools\build.ps1, do not edit this file"
Add-Line "	directly, edit the files under src\ instead."
Add-Line ""
Add-Line "	Interface library: Rayfield (Sirius Software Ltd, MIT licence),"
Add-Line "	vendored from SiriusSoftwareLtd/Rayfield."
Add-Line "]]"
Add-Line ""
Add-Line "local __MOD = {}"
Add-Line ""
Add-Line "local function __define(name, chunk)"
Add-Line "	__MOD[name] = chunk"
Add-Line "end"
Add-Line ""

# Rayfield first, the hub needs it. The library is loaded inside a pcall,
# because it fetches its window from a Roblox asset at load time and a lot
# of executors block that call. A failure must not take the suite down.
$rayfield = Read-Lua (Join-Path $vendor "source.lua")
Add-Line "-- ==== Rayfield ==============================================="
Add-Line "do"
Add-Line "	local ok, library = pcall(function()"
Add-Line $rayfield
Add-Line "	end)"
Add-Line "	if ok and type(library) == ""table"" then"
Add-Line "		__define(""Rayfield"", library)"
Add-Line "	else"
Add-Line "		print(""[AOTR] the Rayfield interface could not be loaded, the built in interface is used"")"
Add-Line "		__define(""Rayfield"", nil)"
Add-Line "	end"
Add-Line "end"
Add-Line ""

foreach ($entry in $modules.GetEnumerator()) {
	$name = $entry.Key
	$path = $entry.Value
	if (-not (Test-Path $path)) {
		throw "Missing module source: $path"
	}
	$code = Read-Lua $path
	Add-Line "-- ==== $name ==============================================="
	Add-Line "__define(""$name"", (function()"
	Add-Line $code
	Add-Line "end)())"
	Add-Line ""
}

Add-Line "-- ==== boot =================================================="
Add-Line "__MOD[""main""](__MOD)"

New-Item -ItemType Directory -Force -Path $dist | Out-Null
$bundleText = $builder.ToString()
[System.IO.File]::WriteAllText($outFile, $bundleText, $utf8NoBom)

$size = [math]::Round((Get-Item $outFile).Length / 1KB, 1)
Write-Host "built $outFile ($size KB)"

# A second build without the Rayfield interface. It has no dependency at
# all and fits into any executor console.
$standaloneFile = Join-Path $dist "AOTR-standalone.lua"
$rayfieldStart = $bundleText.IndexOf("-- ==== Rayfield ===")
$rayfieldEnd = $bundleText.IndexOf("-- ==== Util ===")
if ($rayfieldStart -ge 0 -and $rayfieldEnd -gt $rayfieldStart) {
	$standaloneText = $bundleText.Substring(0, $rayfieldStart) +
		"__define(""Rayfield"", nil)" + "`n`n" +
		$bundleText.Substring($rayfieldEnd)
	[System.IO.File]::WriteAllText($standaloneFile, $standaloneText, $utf8NoBom)
	$standaloneSize = [math]::Round((Get-Item $standaloneFile).Length / 1KB, 1)
	Write-Host "built $standaloneFile ($standaloneSize KB)"

	# The same without the boot line, for the test harness.
	$standaloneModFile = Join-Path $dist "AOTR-standalone.mod.lua"
	$standaloneModText = $standaloneText -replace '__MOD\["main"\]\(__MOD\)', 'return __MOD'
	[System.IO.File]::WriteAllText($standaloneModFile, $standaloneModText, $utf8NoBom)
}

# The same bundle without the boot line, the test harness runs it under a
# mock of the Roblox api.
$moduleFile = Join-Path $dist "AOTR.mod.lua"
$moduleText = $bundleText -replace '__MOD\["main"\]\(__MOD\)', 'return __MOD'
[System.IO.File]::WriteAllText($moduleFile, $moduleText, $utf8NoBom)
Write-Host "built $moduleFile"

# ---------------------------------------------------------------------------
# The loader is generated from src\Loader.lua so it stays testable, the
# shipped file is a single pasteable chunk.
# ---------------------------------------------------------------------------

$loaderSource = Read-Lua (Join-Path $src "Loader.lua")
$loaderHeader = Read-Lua (Join-Path $src "loader_header.txt")
$loaderBuilder = New-Object System.Text.StringBuilder
function Add-LoaderLine([string]$line) {
	[void]$loaderBuilder.AppendLine($line)
}

Add-LoaderLine $loaderHeader
Add-LoaderLine "local __AOTRLoader = (function()"
Add-LoaderLine $loaderSource
Add-LoaderLine "end)()"
Add-LoaderLine ""
Add-LoaderLine "__AOTRLoader({"
Add-LoaderLine "	urls = {"
Add-LoaderLine "		""https://raw.githubusercontent.com/v01dst/AOTR-Suite/main/dist/AOTR.lua"","
Add-LoaderLine "	},"
Add-LoaderLine "	file = ""AOTR.lua"","
Add-LoaderLine "})"

$loaderFile = Join-Path $dist "loader.lua"
[System.IO.File]::WriteAllText($loaderFile, $loaderBuilder.ToString(), $utf8NoBom)
Write-Host "built $loaderFile"
